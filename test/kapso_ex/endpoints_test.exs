  test "every documented operation has a function" do
    covered = Enum.map(calls(), &elem(&1, 0)) ++ @tested_elsewhere

    assert @documented -- covered == [], "operations without a function"
    assert covered -- @documented == [], "functions for operations that are not documented"
  end

  test "each function sends its documented method and path" do
    capture()
    client = client()

    for {operation, call} <- calls() do
      [api, method, template] = String.split(operation, " ")
      expected_path = base_path(api) <> String.replace(template, ~r/\{(\w+)\}/, "\\1")

      assert {:ok, _} = call.(client), operation
      assert_received {:request, %{method: actual_method, path: actual_path}}
      assert {actual_method, actual_path} == {method, expected_path}, operation
    end
  end

